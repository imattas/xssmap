VENDOR_BY_KEY = {v.key: v for v in VENDORS}

# Ordered by how often a strategy pays off; used to cap the extra requests.
STRATEGY_ORDER = (
    "case", "js-split", "js-entity", "tab-space", "comment-pad", "js-unicode",
    "js-b64", "unclosed", "nested-tag", "event-swap", "unicode", "json-escape",
)


class AdaptiveEvasion:
    """Remembers which evasion strategy actually got a payload through.

    Vendor tables are a guess about the target; the target itself is the better
    source. A strategy that made a payload reflect verbatim on an earlier point
    is tried first on the next one, and one that only produced mangled or
    blocked responses is demoted to the end of the budget. The order is still
    bounded by the caller: this only reorders what was going to be tried.
    """

    def __init__(self) -> None:
        self.hits: dict[str, int] = {}
        self.misses: dict[str, int] = {}

    def record(self, strategy: str, worked: bool) -> None:
        if not strategy:
            return
        target = self.hits if worked else self.misses
        target[strategy] = target.get(strategy, 0) + 1

    def score(self, strategy: str) -> tuple[int, int]:
        """Sort key: proven strategies first, then untried ones."""
        hits = self.hits.get(strategy, 0)
        misses = self.misses.get(strategy, 0)
        if hits:
            return (0, -hits)
        if misses:
            return (1, misses)
        return (0, 0)

    def rank(self, strategies: tuple[str, ...] | list[str]) -> tuple[str, ...]:
        """``strategies`` ordered by observed effect, original order breaking ties."""
        unique = list(dict.fromkeys(strategies))
        return tuple(sorted(unique, key=self.score))

    def describe(self) -> str:
        parts = []
        if self.hits:
            parts.append("worked: " + ", ".join(
                f"{k} x{v}" for k, v in sorted(self.hits.items())))
        if self.misses:
            parts.append("filtered: " + ", ".join(
                f"{k} x{v}" for k, v in sorted(self.misses.items())))
        return "; ".join(parts)

# Fullwidth and small-form variants. A filter that compares bytes sees something
# inert; an application that runs NFKC normalisation before the sink turns it
# back into markup. Cheap to try, and it is one of the few techniques that works
# against filters that block the character outright.
_UNICODE_MAP = {
    "<": "\uff1c", ">": "\uff1e", '"': "\uff02", "'": "\uff07",
    "(": "\uff08", ")": "\uff09", "=": "\uff1d", "/": "\uff0f",
    ";": "\uff1b", "`": "\uff40",
}

# JSON sinks unescape these before use, so a rule matching "<script" misses the
# escaped spelling while the application still ends up with the tag.
_JSON_MAP = {"<": "\\u003c", ">": "\\u003e", "&": "\\u0026",
             "'": "\\u0027", '"': "\\u0022"}


@dataclass
class Probe:
    label: str
    status: int
    length: int
    blocked: bool = False
    note: str = ""

    def as_dict(self) -> dict:
        return {"probe": self.label, "status": self.status, "length": self.length,
                "blocked": self.blocked, "note": self.note}


@dataclass
class WAFDetection:
    vendor: str = ""
    name: str = ""
    confidence: str = "none"          # none / low / medium / high
    blocking: bool = False
    evidence: list[str] = field(default_factory=list)
    baseline_status: int = 0
    probes: list[Probe] = field(default_factory=list)
    checked: bool = False

    @property
    def detected(self) -> bool:
        return bool(self.vendor or self.blocking)

    @property
    def evasive(self) -> bool:
        """Should the scanner spend extra requests on evasion for this target?"""
        if not self.detected:
            return False
        if self.blocking:
            return True
        # A recognised product that has not blocked us yet still gets its
        # strategy list; confidence gates how much we spend elsewhere.
        return self.confidence in ("medium", "high")

    def vendor_key(self) -> str:
        return self.vendor or "generic"

    def strategies(self) -> tuple[str, ...]:
        vendor = VENDOR_BY_KEY.get(self.vendor)
        if vendor is not None:
            return vendor.strategies
        # No percent/double-percent entry: the HTTP layer already encodes every
        # value once, so encoding it again is not a bypass, only extra traffic.
        return ("case", "js-entity", "js-split", "unicode")

    def describe(self) -> str:
        if not self.checked:
            return "WAF: not checked"
        if not self.detected:
            return "WAF: none detected"
        label = self.name or "unidentified filter"
        bits = [f"WAF: {label} ({self.confidence} confidence)",
                "blocking" if self.blocking else "not blocking"]
        if self.evidence:
            bits.append(self.evidence[0][:110])
        return "; ".join(bits)

    def summary(self) -> str:
        return self.describe()

    def as_dict(self) -> dict:
        return {
            "checked": self.checked,
            "vendor": self.vendor,
            "name": self.name,
            "confidence": self.confidence,
            "blocking": self.blocking,
            "evidence": list(self.evidence),
            "baseline_status": self.baseline_status,
            "probes": [p.as_dict() for p in self.probes],
            "strategies": list(self.strategies()) if self.detected else [],
        }


