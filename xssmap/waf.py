def _with_param(url: str, name: str, value: str) -> str:
    """Replace (or add) one query parameter without touching the rest."""
    parts = urllib.parse.urlsplit(url)
    pairs = urllib.parse.parse_qsl(parts.query, keep_blank_values=True)
    pairs = [(k, v) for k, v in pairs if k != name]
    pairs.append((name, value))
    return urllib.parse.urlunsplit(
        (parts.scheme, parts.netloc, parts.path, urllib.parse.urlencode(pairs), ""))


def _match(resp) -> list[tuple[Vendor, str, int]]:
    """Return (vendor, evidence, weight) for every signature this response hits."""
    hits: list[tuple[Vendor, str, int]] = []
    headers = getattr(resp, "headers", []) or []
    header_blob = "\n".join(f"{k}: {v}" for k, v in headers)
    cookies = ""
    for name, value in headers:
        if name.lower() == "set-cookie":
            cookies += value.split(";", 1)[0] + "\n"
    try:
        body = (resp.text or "")[:200000]
    except Exception:
        body = ""
    for vendor in VENDORS:
        for rx in vendor.header_rx:
            pattern = rx[4:] if rx.startswith("(?i)") else rx
            hit = ""
            for name, value in headers:
                try:
                    if re.search(pattern, name, re.I) or re.search(
                            pattern, f"{name}: {value}", re.I):
                        hit = f"{name}: {value}"
                        break
                except re.error:
                    continue
            if not hit:
                try:
                    found = re.search(pattern, header_blob, re.I | re.M)
                except re.error:
                    found = None
                hit = found.group(0).strip() if found else ""
            if hit:
                weight = 2 if "server" in pattern.lower() else 3
                hits.append((vendor, f"header: {hit[:80]}", weight))
                break
        for rx in vendor.cookie_rx:
            # Cookie lines are "name=value"; a trailing ``$`` would never match,
            # so anchor on the name prefix instead.
            try:
                found = re.search(rx.replace("$", ""), cookies, re.I | re.M)
            except re.error:
                continue
            if found:
                hits.append((vendor, f"cookie: {found.group(0)[:60]}", 3))
                break
        for rx in vendor.body_rx:
            try:
                found = re.search(rx, body, re.I | re.M)
            except re.error:
                continue
            if found:
                hits.append((vendor, f"body: {found.group(0)[:70]}", 2))
                break
    return hits


def _tally(hits: list[tuple[Vendor, str, int]]) -> tuple[Vendor | None, list[str], int]:
    """Pick the vendor with the strongest evidence; ties go to the first entry."""
    if not hits:
        return None, [], 0
    scores: dict[str, int] = {}
    evidence: dict[str, list[str]] = {}
    vendor_map: dict[str, Vendor] = {}
    for vendor, why, weight in hits:
        scores[vendor.key] = scores.get(vendor.key, 0) + weight
        evidence.setdefault(vendor.key, []).append(why)
        vendor_map[vendor.key] = vendor
    best = max(scores, key=lambda k: scores[k])
    return vendor_map[best], evidence[best], scores[best]


def _confidence(score: int, blocking: bool) -> str:
    if score >= 6 or (score >= 3 and blocking):
        return "high"
    if score >= 3 or blocking:
        return "medium"
    if score >= 1:
        return "low"
    return "none"


PROBES = (
    ("xss-tag", "<script>alert(1)</script>"),
    ("sqli-quote", "' OR 1=1-- x"),
    ("traversal", "../../../../etc/passwd"),
)


def detect(http, url: str, headers: list[tuple[str, str]] | None = None,
           log=None) -> WAFDetection:
    """Probe one URL and decide whether a WAF is present and blocking.

    Costs four requests. Unknown parameters are appended to the query string,
    which firewalls inspect even when the application ignores them.
    """
    result = WAFDetection(checked=True)
    headers = list(headers or [])
    pairs = urllib.parse.parse_qsl(urllib.parse.urlsplit(url).query,
                                   keep_blank_values=True)
    name = pairs[0][0] if pairs else "xsmap_probe"

    def target(value: str) -> str:
        return _with_param(url, name, value)

    try:
        baseline = http.get(target("xsmapwaf1"), headers=headers)
    except Exception as exc:
        result.evidence.append(f"baseline request failed: {str(exc)[:90]}")
        if log:
            log.debug(f"    WAF probe skipped: {exc}")
        return result
    result.baseline_status = baseline.status

    vendor, evidence, score = _tally(_match(baseline))
    if vendor is not None:
        result.vendor, result.name = vendor.key, vendor.name
        result.evidence.extend(evidence)

    for label, value in PROBES:
        try:
            resp = http.get(target(value), headers=headers)
        except Exception as exc:
            result.probes.append(Probe(label, 0, 0, note=str(exc)[:80]))
            continue
        hit_vendor, hit_evidence, hit_score = _tally(_match(resp))
        blocked = False
        note = ""
        if resp.status in BLOCK_STATUSES and result.baseline_status not in BLOCK_STATUSES:
            blocked = True
            note = f"status {resp.status} (baseline {result.baseline_status})"
        elif resp.status >= 400 and resp.status != result.baseline_status:
            note = f"status {resp.status} (baseline {result.baseline_status})"
        body_hit = [why for why in hit_evidence if why.startswith("body:")]
        baseline_body = any(why.startswith("body:") for why in evidence)
        if body_hit and not baseline_body:
            blocked = True
            note = (note + "; " if note else "") + body_hit[0]
        result.probes.append(Probe(label, resp.status, len(resp.body or b""),
                                   blocked=blocked, note=note))
        if hit_vendor is not None and vendor is None:
            vendor, evidence, score = hit_vendor, hit_evidence, hit_score
            result.vendor, result.name = vendor.key, vendor.name
            result.evidence.extend(hit_evidence)
        elif hit_vendor is not None and vendor is not None \
                and hit_vendor.key == vendor.key:
            # Same product, stronger evidence: a block page proves far more than
            # a passive header, and the confidence score must reflect it.
            score = max(score, hit_score)
            for why in hit_evidence:
                if why not in result.evidence:
                    result.evidence.append(why)
        if blocked:
            result.blocking = True
            if note and note not in result.evidence:
                result.evidence.append(note)

    result.confidence = _confidence(score, result.blocking)
    if result.blocking and vendor is None:
        result.name = "unidentified filter"
        result.confidence = "low"
        result.evidence.append("hostile probe answered differently from the baseline")
    if log and result.detected:
        log.warn("  " + result.describe())
    return result


