"""Web application firewall fingerprinting and vendor-aware evasion.

Two questions, answered from traffic rather than assumption:

1. *Is something filtering us, and what is it?* A handful of benign and hostile
   probes compared against a baseline reveal both the product (response headers,
   cookies, block-page text) and whether it is actively blocking this target.

2. *Given that product, which payload shapes have a chance?* Each vendor gets a
   short list of encodings and JavaScript wrappers that are known to slip past
   its rule set. They are applied as extra candidates, never instead of the
   plain payload, and every one still has to reflect and execute to be reported.

Nothing here weakens the honesty rules elsewhere in the scanner: an evasion
variant is a hypothesis like any other payload. If it does not survive and
execute, it produces no finding.
"""
from __future__ import annotations

import base64
import re
import urllib.parse
from dataclasses import dataclass, field

from . import contexts
from .filters import mutate

# Proxy/WAF block statuses. 400 is only treated as a block when the body also
# carries a vendor signature, because applications use it for validation too.
BLOCK_STATUSES = (403, 406, 429, 501, 503)

# Markup-level tricks (case, comments, tag splitting) only mean anything where
# HTML markup is parsed; the registry decides that once for the whole codebase.
MARKUP_CONTEXTS = contexts.MARKUP_CONTEXTS


